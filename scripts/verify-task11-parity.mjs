import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import sharp from "sharp";

const base = process.argv[2] || "8100a58";
const origin = process.argv[3] || "http://127.0.0.1:41777";
const root = resolve(new URL("..", import.meta.url).pathname);
const output = join(tmpdir(), `portfolio-task11-parity-${process.pid}`);
const playwrightPath = process.env.CODEX_PLAYWRIGHT_PATH || "/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs";
const { chromium } = await import(pathToFileURL(playwrightPath));
const routes = {
  home: "/index.html",
  work: "/work.html",
  tedx: "/work/tedx-rsu.html",
  about: "/about.html",
  services: "/services.html",
  contact: "/contact.html"
};
const cssFiles = ["foundations.css", "components-v4.css", "pages-v4.css"];
const baseline = Object.fromEntries(cssFiles.map(name => [name, execFileSync("git", ["show", `${base}:styles/${name}`], { cwd: root, encoding: "utf8" })]));
const stableStyle = "img,picture,.decision-field__canvas,.site-footer__signature-canvas{visibility:hidden!important}.client-marquee__track{animation:none!important;transform:none!important}";
const sha256 = buffer => createHash("sha256").update(buffer).digest("hex");

await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const records = [];
try {
  for (const phase of ["before", "after"]) for (const [route, pathname] of Object.entries(routes)) for (const width of [390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, colorScheme: "light", reducedMotion: "reduce" });
    const page = await context.newPage();
    if (phase === "before") await page.route(/styles\/(foundations|components-v4|pages-v4)\.css$/, request => {
      const name = request.request().url().match(/(foundations|components-v4|pages-v4)\.css$/)[1] + ".css";
      return request.fulfill({ contentType: "text/css", body: baseline[name] });
    });
    await page.goto(origin + pathname, { waitUntil: "domcontentloaded" });
    await page.evaluate(() => document.fonts.ready);
    await page.locator(".site-nav").waitFor();
    const file = join(output, `${phase}-${route}-${width}.png`);
    await page.screenshot({ path: file, animations: "disabled", style: stableStyle });
    const buffer = await readFile(file);
    const metadata = await sharp(buffer).metadata();
    records.push({ phase, route, pathname, width, height: metadata.height, pixelWidth: metadata.width, bytes: buffer.byteLength, sha256: sha256(buffer), file });
    await context.close();
  }
} finally { await browser.close(); }

const pairs = [];
for (const route of Object.keys(routes)) for (const width of [390, 1440]) {
  const before = records.find(record => record.phase === "before" && record.route === route && record.width === width);
  const after = records.find(record => record.phase === "after" && record.route === route && record.width === width);
  const beforePixels = await sharp(before.file).ensureAlpha().raw().toBuffer();
  const afterPixels = await sharp(after.file).ensureAlpha().raw().toBuffer();
  let changedBytes = 0;
  for (let index = 0; index < beforePixels.length; index += 1) if (beforePixels[index] !== afterPixels[index]) changedBytes += 1;
  pairs.push({ route, pathname: before.pathname, width, height: before.height, beforeSha256: before.sha256, afterSha256: after.sha256, changedBytes, identical: changedBytes === 0 });
}
if (pairs.some(pair => !pair.identical)) throw new Error(`Task 11 screenshot parity failed:\n${JSON.stringify(pairs, null, 2)}`);

const manifest = {
  schemaVersion: 1,
  baselineCommit: base,
  currentCssSha256: sha256(Buffer.from(await Promise.all(cssFiles.map(name => readFile(join(root, "styles", name), "utf8"))).then(parts => parts.join("\n")))),
  capture: { viewportHeight: 900, colorScheme: "light", reducedMotion: "reduce", stableStyle, screenshots: "temporary files generated by scripts/verify-task11-parity.mjs" },
  pairs
};
await writeFile(join(root, "reports/qa/task11-parity-manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`Task 11 screenshot parity passed: ${pairs.length}/${pairs.length}; manifest written to reports/qa/task11-parity-manifest.json.`);
