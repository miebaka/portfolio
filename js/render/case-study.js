/* Render — case study: one shared template for every project page.

   Rebuilt around the presentation model shared by belonwus.com and
   portorocha.com: the work carries the argument, not an essay about it.
   Both sites open on a full-bleed image, state the project in a single line,
   compress the facts into a small label/value block, and then run a long
   image sequence in one rhythm (3:2 landscape bands, uprights paired two-up)
   before an onward link. Neither uses Challenge / Process / Solution prose.

   The written sections still live in data/site.js and are not deleted; this
   template simply renders the short-form of them under "Project information"
   so nothing is lost if the long form is ever wanted back. */
import { SITE } from "../../data/site.js";
import { escapeHTML as esc, safeToken, mount, basePath } from "../utilities/dom.js";
import { MOUNT } from "../core/contract.js";

/* Widths generated by scripts/optimize-images.mjs. */
const BLEED_WIDTHS = [540, 810, 1080, 1440, 1920];

function paras(list) {
  return (list || []).map((p) => "<p>" + esc(p) + "</p>").join("");
}

/* Anything squarer than 1.2:1 is treated as upright and pairs two-up, which
   is how both references handle posters and packaging. Landscape work runs
   as a single band. */
function isUpright(m) {
  return Boolean(m && m.w && m.h && m.w / m.h < 1.2);
}

/* One image. `kind` is "hero", "band" or "pair" and only affects sizing:
   the markup and the srcset ladder are identical in all three. */
function shot(m, kind) {
  if (!m) return "";
  if (!m.src) {
    return (
      '<figure class="case-shot case-shot--' + kind + ' case-shot--empty reveal">' +
      '<span class="case-shot__placeholder">' + esc(m.label) + "</span></figure>"
    );
  }

  const base = basePath() + "assets/images/optimized/" + safeToken(m.src);
  /* The optimizer never upscales, so no variant exists above the master's own
     width. Advertising one anyway lets the browser pick a 404 and render a
     broken image, since a missing <source> candidate is not retried. */
  const widths = BLEED_WIDTHS.filter((w) => !m.w || w <= m.w);
  const fallback = widths.includes(1080) ? 1080 : widths[widths.length - 1];
  const set = (ext) => widths.map((w) => base + "-" + w + "." + ext + " " + w + "w").join(", ");
  const sizes = kind === "pair" ? "(max-width: 50rem) 100vw, 43vw" : "100vw";
  /* The hero is the LCP element on every case page, so it opts out of lazy
     loading and asks for priority instead. */
  const load = kind === "hero"
    ? ' fetchpriority="high" decoding="async"'
    : ' loading="lazy" decoding="async"';

  return (
    '<figure class="case-shot case-shot--' + kind + ' reveal">' +
      "<picture>" +
        '<source type="image/avif" srcset="' + set("avif") + '" sizes="' + sizes + '">' +
        '<source type="image/webp" srcset="' + set("webp") + '" sizes="' + sizes + '">' +
        '<img src="' + base + "-" + fallback + '.jpg" alt="' + esc(m.alt || m.label) + '"' +
          ' width="' + m.w + '" height="' + m.h + '"' + load + ">" +
      "</picture>" +
    "</figure>"
  );
}

/* Walks the media list once, emitting a band per landscape image and pairing
   consecutive uprights. A lone upright at the end falls back to a band so it
   never renders as a half-width orphan. */
function sequence(media) {
  let out = "";
  for (let i = 0; i < media.length; i++) {
    const m = media[i];
    if (isUpright(m) && isUpright(media[i + 1])) {
      out +=
        '<div class="case-pair">' + shot(m, "pair") + shot(media[i + 1], "pair") + "</div>";
      i++;
      continue;
    }
    out += shot(m, isUpright(m) ? "upright" : "band");
  }
  return out;
}

/* Client / Year / Services laid across the grid, as in the reference. Industry
   rides along with Client rather than claiming a fourth column, which keeps
   the row to the three the reference uses. */
function factsBlock(c, project) {
  const r = c.rail || {};
  const rows = [
    ["Role", r.services],
    ["Scope", r.meta],
    ["Constraint", c.overview && c.overview.question],
    ["Outcome", c.outcome && c.outcome.body && c.outcome.body[0]],
  ].filter(([, v]) => v);
  return (
    '<dl class="case-facts">' +
    rows
      .map(
        ([k, v]) =>
          '<div class="case-facts__cell">' +
          "<dt>" + esc(k) + "</dt><dd>" + esc(v) + "</dd></div>"
      )
      .join("") +
    "</dl>"
  );
}

function metricsBlock(outcome) {
  const o = outcome || {};
  if (!o.metrics || !o.metrics.length) return "";
  return (
    '<section class="case-metrics container reveal" aria-label="Outcome">' +
    o.metrics
      .map(
        (m) =>
          '<div class="case-metric"><strong>' + esc(m.value) +
          "</strong><span>" + esc(m.label) + "</span></div>"
      )
      .join("") +
    "</section>"
  );
}

function chapter(id, title, heading, body, media, featured) {
  const visual = media && media.length
    ? '<div class="case-chapter__media' + (featured ? ' case-chapter__media--feature' : '') + '">' + sequence(media) + '</div>'
    : "";
  return (
    '<section class="case-chapter" id="' + id + '" aria-labelledby="' + id + '-title">' +
      '<div class="case-chapter__copy container reveal">' +
        '<p class="case-chapter__label">' + esc(title) + '</p>' +
        '<h2 id="' + id + '-title">' + esc(heading) + '</h2>' +
        '<div class="case-chapter__body">' + paras(body) + '</div>' +
      '</div>' + visual +
    '</section>'
  );
}

function chapterRail() {
  return (
    '<nav class="case-rail" aria-label="Case study chapters" hidden>' +
      '<a href="#problem">Problem</a>' +
      '<a href="#decision">Decision</a>' +
      '<a href="#system">System</a>' +
      '<a href="#applications">Applications</a>' +
      '<a href="#result">Result</a>' +
    '</nav>'
  );
}

export function renderCaseStudy() {
  const slug = document.body.dataset.case;
  if (!slug) return;
  const el = mount(MOUNT.CASE);
  if (!el) return;

  /* hasOwnProperty rather than a bare lookup: data-case comes from markup, and
     a plain index would happily return inherited members like "constructor"
     or "toString" and then throw partway through building the page. */
  const studies = SITE.caseStudies || {};
  if (!Object.prototype.hasOwnProperty.call(studies, slug)) return;
  const c = studies[slug];
  if (!c) return;

  const base = basePath();
  const media = c.media || [];
  const project = (SITE.projects || []).find((p) => p.slug === slug);

  const hero = media[0];
  const rest = media.slice(1);
  const groups = [[], [], [], [], []];
  rest.forEach((item, index) => groups[Math.min(4, Math.floor(index * 5 / Math.max(1, rest.length)))].push(item));
  const overview = c.overview || {};
  const outcome = c.outcome || {};

  /* The next-project link is optional. Without this guard a study missing
     `next` threw at the very end, after the whole article had been built,
     leaving the mount empty. */
  const next = c.next && c.next.slug
    ? '<section class="case-next container reveal" aria-label="Next project">' +
      '<p class="case-next__label">Next project</p>' +
      '<a class="case-next__link" href="' + base + "work/" + esc(c.next.slug) + '.html">' +
      esc(c.next.title) + " &rarr;</a></section>"
    : "";

  /* Opening image, facts, proposition, chapters, outcome and next project. */
  el.innerHTML =
    chapterRail() +
    shot(hero, "hero") +
    '<header class="case-lede container">' +
      factsBlock(c, project) +
      '<h1 class="case-statement reveal">' + esc(c.tagline) + "</h1>" +
      '<div class="case-brief reveal">' + paras(overview.body || []) + "</div>" +
    "</header>" +
    chapter("problem", "Problem", overview.question || "The problem", c.challenge || [], groups[0], false) +
    chapter("decision", "Decision", "The idea underneath the form", c.process || [], groups[1], true) +
    chapter("system", "System", "One decision, carried through", c.solution || [], groups[2], false) +
    chapter("applications", "Applications", "The system in the world", ["The identity was tested where it had to work: across the practical surfaces, scales and contexts the audience would actually encounter."], groups[3], false) +
    chapter("result", "Result", "What the system made possible", outcome.body || [], groups[4], false) +
    metricsBlock(outcome) +
    next;
}
